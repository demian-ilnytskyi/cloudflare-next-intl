/** Escapes a value on its way into email markup — links and stored names both reach the HTML body, and stored data is never trusted there. */
export function escapeHtml(value: string): string {
    return value
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;');
}
